#: ``subprocess`` above is imported for exactly one call site: the updater the
#: user has explicitly confirmed by absolute path.  Nothing else here shells out.

VERSION_FILE = "comfyui_version.py"
_VERSION_RE = re.compile(r"""__version__\s*=\s*['"]([^'"]+)['"]""")

#: Update mechanisms, most specific first.  Each entry is
#: (id, relative path from the *parent* of the ComfyUI folder, label).
PORTABLE_UPDATERS: tuple[tuple[str, str, str], ...] = (
    ("portable_stable", os.path.join("update", "update_comfyui_stable.bat"),
     "Portable updater - stable releases only"),
    ("portable", os.path.join("update", "update_comfyui.bat"),
     "Portable updater - latest master"),
    ("portable_with_deps",
     os.path.join("update", "update_comfyui_and_python_dependencies.bat"),
     "Portable updater - also reinstalls Python dependencies"),
)

#: Ports ComfyUI listens on by default.  Used only to refuse an update while it
#: looks like it is running (C8.3).
COMFYUI_PORTS = (8188, 8189)

PACKAGE_INTEREST = (
    "comfyui_frontend_package", "comfyui_workflow_templates",
    "comfyui_workflow_templates_core", "comfyui_workflow_templates_json",
    "comfyui_embedded_docs", "comfyui_manager", "comfy_config",
)

LATEST_ENDPOINTS = (
    ("github", "https://api.github.com/repos/comfyanonymous/ComfyUI/releases/latest"),
    ("pypi", "https://pypi.org/pypi/comfyui/json"),
)
LATEST_TTL_MS = 6 * 60 * 60 * 1000
NETWORK_TIMEOUT_S = 8.0

UPDATE_CHANNEL = progress.bus("comfyui_update")

_run_lock = threading.Lock()
_run_state: dict = {"status": "idle"}


