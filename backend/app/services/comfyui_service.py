def report(cfg=None) -> dict:
    """The read-only C8 panel payload."""
    install = probe(cfg)
    if install.root is None:
        return {"configured": False, "comfyui_path": None, "version": None,
                "flavour": "unknown", "updaters": [], "packages": {},
                "running": {"running": False, "ports": []}}
    return {
        "configured": True,
        "comfyui_path": str(install.root),
        "install_parent": str(install.parent) if install.parent else None,
        "version": install.version,
        "version_source": install.version_source,
        "flavour": install.flavour,
        "flavour_evidence": install.flavour_reasons,
        "python_home": install.python,
        "git": install.git,
        "packages": install.packages,
        "updaters": install.updaters,
        "recommended_updater": next(
            (u["id"] for u in install.updaters if u["recommended"]), None),
        "running": is_running(),
        "update_status": update_status(),
    }
