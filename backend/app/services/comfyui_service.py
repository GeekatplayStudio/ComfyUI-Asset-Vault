def _cache_get(key: str) -> dict | None:
    try:
        row = dbmod.one(
            dbmod.get_ro(),
            "SELECT body_json, fetched_at, expires_at, status FROM http_cache "
            "WHERE cache_key = ?", (key,))
    except Exception:  # noqa: BLE001
        return None
    if row is None or int(row["expires_at"] or 0) < dbmod.now_ms():
        return None
    import json

    try:
        return {"body": json.loads(row["body_json"] or "{}"),
                "fetched_at": int(row["fetched_at"] or 0), "cached": True}
    except ValueError:
        return None


def _cache_put(key: str, provider: str, body: dict) -> None:
    import json

    now = dbmod.now_ms()

    def _op(conn) -> None:
        conn.execute("BEGIN IMMEDIATE")
        conn.execute(
            "INSERT INTO http_cache(cache_key,provider,status,body_json,etag,"
            "fetched_at,expires_at,error) VALUES (?,?,?,?,NULL,?,?,NULL) "
            "ON CONFLICT(cache_key) DO UPDATE SET status=excluded.status, "
            "body_json=excluded.body_json, fetched_at=excluded.fetched_at, "
            "expires_at=excluded.expires_at, error=NULL",
            (key, provider, 200, json.dumps(body, default=str)[:200_000], now,
             now + LATEST_TTL_MS),
        )
        conn.commit()

    try:
        dbmod.writer().run(_op)
    except Exception as exc:  # noqa: BLE001 - a cold cache is not a failure
        log.debug("version cache write failed: %s", exc)


def _norm_version(value: str | None) -> tuple[int, ...]:
    if not value:
        return ()
    cleaned = str(value).strip().lstrip("vV")
    parts: list[int] = []
    for chunk in re.split(r"[.\-+_]", cleaned):
        if chunk.isdigit():
            parts.append(int(chunk))
        else:
            break
    return tuple(parts)


def compare_versions(installed: str | None, latest: str | None) -> str:
    a, b = _norm_version(installed), _norm_version(latest)
    if not a or not b:
        return "unknown"
    if b > a:
        return "behind"
    if b < a:
        return "ahead"
    return "current"


async def check_latest(*, force: bool = False) -> dict:
    """Look up the newest published ComfyUI release.

    Strictly read-only and strictly optional.  Offline, blocked, rate-limited and
    "online enrichment is switched off" all resolve to a plain answer with a
    reason, never an error - the Storage and Version panels must render with no
    network at all.
    """
    install = probe()
    cfg = config_service.get_config()
    base = {
        "installed": install.version,
        "installed_source": install.version_source,
        "latest": None, "state": "unknown", "checked_at": None,
        "source": None, "cached": False, "reason": None,
        "release_url": None, "release_notes": None,
    }

    if not force:
        for provider, _url in LATEST_ENDPOINTS:
            hit = _cache_get(f"comfyui:latest:{provider}")
            if hit:
                body = hit["body"]
                return {**base, "latest": body.get("version"),
                        "state": compare_versions(install.version,
                                                  body.get("version")),
                        "checked_at": hit["fetched_at"], "source": provider,
                        "cached": True, "release_url": body.get("url"),
                        "release_notes": body.get("notes"),
                        "reason": None}

    if not cfg.online_enabled:
        return {**base, "reason": "online_disabled",
                "hint": "Enable online lookups in Settings to check for updates."}

    import httpx

    last_error: str | None = None
    for provider, url in LATEST_ENDPOINTS:
        try:
            async with httpx.AsyncClient(timeout=NETWORK_TIMEOUT_S,
                                         follow_redirects=True) as client:
                response = await client.get(
                    url, headers={"Accept": "application/json",
                                  "User-Agent": "GeekatplayComfyUIAssetVault/2.0"})
            if response.status_code == 429:
                last_error = "rate_limited"
                continue
            if response.status_code >= 400:
                last_error = f"http_{response.status_code}"
                continue
            payload = response.json()
        except Exception as exc:  # noqa: BLE001 - offline is a normal state
            last_error = type(exc).__name__
            continue

        if provider == "github":
            body = {"version": str(payload.get("tag_name") or "").lstrip("vV"),
                    "url": payload.get("html_url"),
                    "notes": (payload.get("body") or "")[:4000]}
        else:
            body = {"version": str(
                (payload.get("info") or {}).get("version") or ""),
                "url": (payload.get("info") or {}).get("project_url"),
                "notes": None}
        if not body["version"]:
            last_error = "no_version_in_response"
            continue
        _cache_put(f"comfyui:latest:{provider}", provider, body)
        return {**base, "latest": body["version"],
                "state": compare_versions(install.version, body["version"]),
                "checked_at": dbmod.now_ms(), "source": provider, "cached": False,
                "release_url": body["url"], "release_notes": body["notes"],
                "reason": None}

    return {**base, "reason": last_error or "offline",
            "hint": "No network. The installed version is still shown above."}


