"""ComfyUI version awareness, updater discovery, the official templates
catalogue, and opening a workflow inside ComfyUI (REQUIREMENTS_R2 C8).

Everything in here is read-only except three functions:
:func:`run_updater` and :func:`start_comfyui`, the only two places this
application ever starts a process, and :func:`copy_into_user_workflows`, the
only place it ever writes into the ComfyUI installation.  Each runs only after
the caller has confirmed the exact resolved absolute path it will act on.

Discovery, not assumption
-------------------------
C8.3 is explicit: find the real update mechanism for *this* install rather than
assuming a layout.  The owner's install is a portable build - ``O:\\ComfyUI`` with
``O:\\python_embeded`` and ``O:\\update\\update_comfyui.bat`` as siblings - so the
updater is neither inside the ComfyUI folder nor a plain ``git pull``.  The probe
below walks the real candidates in priority order and reports every one it found,
so the UI can show what will run before anything runs.

Version sources
---------------
``comfyui_version.py`` carries ``__version__`` and is generated by ComfyUI's own
build, so it is the authoritative installed version.  Frontend and template
package versions come from ``*.dist-info`` directory names in the interpreter
that actually launches ComfyUI, which for a portable build is ``python_embeded``
and not the interpreter this app runs under.
"""

