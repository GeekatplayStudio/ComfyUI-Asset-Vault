TEMPLATE_PACKAGES = ("comfyui_workflow_templates_json", "comfyui_workflow_templates")


def template_catalogue(install: Install | None = None, *, limit: int = 100,
                       offset: int = 0, bundle: str | None = None,
                       q: str | None = None) -> dict:
    """The official ComfyUI templates shipped with this install (C8.4).

    These are catalogued, not indexed as vault rows, and that is deliberate: they
    live inside the Python distribution that runs ComfyUI, and making them vault
    assets would put ComfyUI's own installed files inside the reach of rename,
    move and delete.  The vault must never be able to damage the installation it
    is describing.
    """
    install = install or probe()
    site = site_packages_of(Path(install.python)) if install.python else None
    result: dict = {"available": False, "reason": None, "package_version": None,
                    "path": None, "bundles": [], "items": [], "total": 0}
    if site is None:
        result["reason"] = "no bundled interpreter found for this install"
        return result

    directory = None
    for package in TEMPLATE_PACKAGES:
        candidate = site / package / "templates"
        if candidate.is_dir():
            directory = candidate
            result["package_version"] = install.packages.get(package)
            break
    if directory is None:
        result["reason"] = "comfyui_workflow_templates is not installed"
        return result

    result["available"] = True
    result["path"] = str(directory)

    manifest = _load_manifest(site, install)
    by_id = {str(t.get("id")): t for t in manifest.get("templates", [])
             if isinstance(t, dict)}
    bundles: dict[str, int] = {}

    items: list[dict] = []
    try:
        entries = sorted(os.scandir(long_path(str(directory))), key=lambda e: e.name)
    except OSError as exc:
        result["available"] = False
        result["reason"] = str(exc)[:200]
        return result

    needle = (q or "").strip().lower()
    for entry in entries:
        if not entry.name.endswith(".json"):
            continue
        template_id = entry.name[:-5]
        meta = by_id.get(template_id) or {}
        template_bundle = str(meta.get("bundle") or "core")
        bundles[template_bundle] = bundles.get(template_bundle, 0) + 1
        if bundle and template_bundle != bundle:
            continue
        title = template_id.replace("_", " ").replace("-", " ").strip()
        if needle and needle not in template_id.lower() and needle not in title.lower():
            continue
        try:
            size = int(entry.stat().st_size)
        except OSError:
            size = 0
        items.append({
            "id": template_id, "title": title[:1].upper() + title[1:],
            "bundle": template_bundle, "filename": entry.name,
            "size": size, "path": entry.path,
            "origin": "official_template",
            "origin_label": "official template",
            "template_version": meta.get("version"),
        })

    result["bundles"] = [{"key": k, "count": v} for k, v in sorted(bundles.items())]
    result["total"] = len(items)
    result["items"] = items[offset:offset + max(1, min(500, int(limit)))]
    result["note"] = (
        "Shipped with ComfyUI itself and listed read-only. They are not indexed "
        "as vault assets, so vault file operations can never touch them."
    )
    return result


def _load_manifest(site: Path, install: Install) -> dict:
    import json

    for package in ("comfyui_workflow_templates_core", "comfyui_workflow_templates"):
        path = site / package / "manifest.json"
        if not path.is_file():
            continue
        try:
            data = json.loads(Path(long_path(path)).read_text(
                encoding="utf-8", errors="replace"))
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            data.setdefault("_package", package)
            data.setdefault("_version", install.packages.get(package))
            return data
    return {}


