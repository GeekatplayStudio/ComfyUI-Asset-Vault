@dataclass
class Install:
    root: Path | None = None
    parent: Path | None = None
    version: str | None = None
    version_source: str | None = None
    flavour: str = "unknown"
    flavour_reasons: list[str] = field(default_factory=list)
    python: str | None = None
    git: dict | None = None
    packages: dict = field(default_factory=dict)
    updaters: list[dict] = field(default_factory=list)


def read_version(root: Path) -> tuple[str | None, str | None]:
    """``__version__`` from ``comfyui_version.py``, parsed, never executed."""
    path = root / VERSION_FILE
    try:
        text = Path(long_path(path)).read_text(encoding="utf-8", errors="replace")
    except OSError:
        text = None
    if text:
        try:
            module = ast.parse(text)
            for node in module.body:
                if not isinstance(node, ast.Assign):
                    continue
                for target in node.targets:
                    if getattr(target, "id", None) == "__version__" and \
                            isinstance(node.value, ast.Constant):
                        return str(node.value.value), VERSION_FILE
        except (SyntaxError, ValueError):
            pass
        m = _VERSION_RE.search(text)
        if m:
            return m.group(1), VERSION_FILE

    pyproject = root / "pyproject.toml"
    try:
        raw = Path(long_path(pyproject)).read_bytes()
    except OSError:
        return None, None
    try:
        import tomllib

        data = tomllib.loads(raw.decode("utf-8", "replace"))
    except (ValueError, UnicodeDecodeError):
        return None, None
    version = ((data.get("project") or {}).get("version")
               or (data.get("tool") or {}).get("comfy", {}).get("version"))
    return (str(version), "pyproject.toml") if version else (None, None)


def _read_git(root: Path) -> dict | None:
    """Git state read as *files*.  No ``subprocess``, no network."""
    gitdir = root / ".git"
    if not gitdir.exists():
        return None
    info: dict = {"present": True, "branch": None, "commit": None,
                  "remote": None, "shallow": False, "worktree": gitdir.is_file()}
    try:
        if gitdir.is_file():
            pointer = Path(long_path(gitdir)).read_text(encoding="utf-8",
                                                        errors="replace")
            if pointer.startswith("gitdir:"):
                candidate = Path(pointer.split(":", 1)[1].strip())
                gitdir = candidate if candidate.is_absolute() else root / candidate
        head = Path(long_path(gitdir / "HEAD")).read_text(
            encoding="utf-8", errors="replace").strip()
        if head.startswith("ref:"):
            ref = head.split(":", 1)[1].strip()
            info["branch"] = ref.rsplit("/", 1)[-1]
            ref_file = gitdir / ref.replace("/", os.sep)
            if ref_file.is_file():
                info["commit"] = Path(long_path(ref_file)).read_text(
                    encoding="utf-8", errors="replace").strip()[:40]
            else:
                packed = gitdir / "packed-refs"
                if packed.is_file():
                    for line in Path(long_path(packed)).read_text(
                            encoding="utf-8", errors="replace").splitlines():
                        if line.endswith(" " + ref):
                            info["commit"] = line.split(" ", 1)[0][:40]
                            break
        else:
            info["commit"] = head[:40]
        info["shallow"] = (gitdir / "shallow").is_file()
        config = gitdir / "config"
        if config.is_file():
            text = Path(long_path(config)).read_text(encoding="utf-8",
                                                     errors="replace")
            m = re.search(r'\[remote "origin"\][^\[]*?url\s*=\s*(\S+)', text, re.S)
            if m:
                info["remote"] = m.group(1).strip()
    except OSError as exc:
        info["error"] = str(exc)[:200]
    return info


def _dist_versions(site_packages: Path) -> dict:
    """Installed distribution versions from ``*.dist-info`` directory names."""
    out: dict[str, str] = {}
    if not site_packages.is_dir():
        return out
    try:
        entries = list(os.scandir(long_path(str(site_packages))))
    except OSError:
        return out
    for entry in entries:
        name = entry.name
        if not name.endswith(".dist-info"):
            continue
        stem = name[: -len(".dist-info")]
        dist, _sep, version = stem.rpartition("-")
        if not dist or not version:
            continue
        key = dist.replace("-", "_").lower()
        if key in PACKAGE_INTEREST or key.startswith("comfyui_workflow_templates"):
            out[key] = version
    return out


def _python_home(parent: Path | None, root: Path) -> Path | None:
    """The interpreter that actually launches ComfyUI, if it ships with it."""
    for candidate in filter(None, (parent, root)):
        for name in ("python_embeded", "python_embedded", "venv", ".venv"):
            home = candidate / name
            if (home / "python.exe").is_file() or (home / "bin" / "python").is_file():
                return home
    return None


def site_packages_of(home: Path | None) -> Path | None:
    if home is None:
        return None
    for rel in (Path("Lib") / "site-packages", Path("lib") / "site-packages"):
        candidate = home / rel
        if candidate.is_dir():
            return candidate
    try:
        for entry in (home / "lib").iterdir():
            candidate = entry / "site-packages"
            if candidate.is_dir():
                return candidate
    except OSError:
        pass
    return None


def discover_updaters(root: Path, parent: Path | None, git: dict | None) -> list[dict]:
    """Every update mechanism that actually exists for THIS install (C8.3)."""
    found: list[dict] = []
    if parent is not None:
        for updater_id, rel, label in PORTABLE_UPDATERS:
            path = parent / rel
            if not path.is_file():
                continue
            found.append({
                "id": updater_id, "kind": "batch", "label": label,
                "path": str(path), "working_dir": str(path.parent),
                "command": [str(path)],
                "available": True, "recommended": updater_id == "portable",
                "note": ("Runs ComfyUI's own updater. It updates the code only; "
                         "use the '_and_python_dependencies' variant only if "
                         "dependencies are broken."),
            })
    if git and git.get("present"):
        exe = shutil.which("git")
        found.append({
            "id": "git", "kind": "git", "label": "git pull in the ComfyUI folder",
            "path": exe, "working_dir": str(root),
            "command": [exe or "git", "pull", "--ff-only"],
            "available": bool(exe), "recommended": not found,
            "note": ("Git checkout detected"
                     + (f" on branch {git.get('branch')}" if git.get("branch") else "")
                     + ("; the repository is shallow, so a fast-forward pull may "
                        "fail and the portable updater is the safer choice."
                        if git.get("shallow") else ".")),
        })
    if found and not any(f["recommended"] for f in found):
        found[0]["recommended"] = True
    return found


def _flavour(root: Path, parent: Path | None, git: dict | None,
             python_home: Path | None) -> tuple[str, list[str]]:
    reasons: list[str] = []
    portable = bool(python_home and python_home.name.startswith("python_embed"))
    if portable:
        reasons.append(f"embedded interpreter at {python_home}")
    if parent is not None and (parent / "update").is_dir():
        reasons.append(f"portable update folder at {parent / 'update'}")
        portable = True
    if parent is not None and any(parent.glob("run_*.bat")):
        reasons.append("portable launcher batch files beside the ComfyUI folder")
        portable = True
    desktop = any(marker in str(root).lower()
                  for marker in ("\\programs\\@comfyorgcomfyui", "comfyui-electron"))
    if desktop:
        reasons.append("desktop application install layout")
        return "desktop", reasons
    if portable:
        if git and git.get("present"):
            reasons.append("also a git checkout (portable builds ship one)")
        return "portable", reasons
    if git and git.get("present"):
        reasons.append(f".git present, remote {git.get('remote') or 'unknown'}")
        return "git", reasons
    reasons.append("no portable launcher, no .git")
    return "manual", reasons


def probe(cfg=None) -> Install:
    """Everything C8.1 asks for, measured from the filesystem."""
    cfg = cfg or config_service.get_config()
    root = cfg.comfyui_path
    if root is None:
        return Install()
    root = Path(normalize(root))
    parent = root.parent if root.parent != root else None
    version, source = read_version(root)
    git = _read_git(root)
    python_home = _python_home(parent, root)
    flavour, reasons = _flavour(root, parent, git, python_home)
    packages = _dist_versions(site_packages_of(python_home) or Path(""))
    return Install(
        root=root, parent=parent, version=version, version_source=source,
        flavour=flavour, flavour_reasons=reasons,
        python=str(python_home) if python_home else None,
        git=git, packages=packages,
        updaters=discover_updaters(root, parent, git),
    )


def is_running() -> dict:
    """Best-effort "is ComfyUI up right now" check (C8.3 refuses to update if so).

    A listening socket on a ComfyUI port is the signal.  It cannot prove the
    process is ComfyUI, so the answer is reported with its evidence and the UI
    says what it saw rather than asserting.
    """
    listening: list[int] = []
    for port in COMFYUI_PORTS:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.settimeout(0.25)
        try:
            if sock.connect_ex(("127.0.0.1", port)) == 0:
                listening.append(port)
        except OSError:
            continue
        finally:
            sock.close()
    return {
        "running": bool(listening),
        "ports": listening,
        "method": "loopback tcp probe",
        "confidence": "inferred",
        "note": ("Something is listening on "
                 + ", ".join(f"127.0.0.1:{p}" for p in listening)
                 + ". Close ComfyUI before updating."
                 if listening else "No ComfyUI port is accepting connections."),
    }


