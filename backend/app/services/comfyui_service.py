#: Ports ComfyUI listens on by default.  Used only to refuse an update while it
#: looks like it is running (C8.3).
COMFYUI_PORTS = (8188, 8189)

#: Files a real ComfyUI checkout or portable build always carries.
#: ``comfyui_version.py`` is generated by ComfyUI's own release process, so a
#: directory that merely holds ``models/`` plus ``main.py`` - which is all
#: ``PATCH /system/config`` requires - does not get it for free.  SECURITY_REVIEW
#: S-04 raised this bar for the updater; S-20 raises it for the launcher, which
#: nominates an executable from the same caller-settable ``comfyui_path``.
INSTALL_PROOF = ("comfyui_version.py", "main.py")


def missing_install_proof(root: Path | None) -> list[str]:
    """What a candidate folder lacks before it may nominate an executable.

    Empty means "this is a real install".  The order and the names are part of
    the API: the updater routes report them as ``details.missing``.
    """
    if root is None or not Path(long_path(root)).is_dir():
        return ["comfyui_path"]
    missing = [name for name in INSTALL_PROOF if not (root / name).is_file()]
    if not (root / "models").is_dir():
        missing.append("models")
    return missing


#: Characters ``cmd.exe`` acts on even when it is handed a command line that was
#: built as a list argv.  SECURITY_REVIEW S-19: a ``.bat``/``.cmd`` target is
#: never executed directly on Windows - ``CreateProcess`` runs it through
#: ``cmd.exe``, which re-parses the *whole* command line - so "list argv,
#: shell=False" does not by itself make the executable's own path an opaque
#: single argument.  ``list2cmdline`` quotes a token only when it contains a
#: space or a tab, so a metacharacter in an otherwise space-free path is live.
#: ``"`` and ``%`` survive quoting; the rest do not.
CMD_UNSAFE_ALWAYS = '"%'
CMD_UNSAFE_UNQUOTED = '&|<>^()!'


def cmd_line_hazard(command) -> str | None:
    """The character ``cmd.exe`` would act on in this argv, or ``None``.

    Only ``.bat``/``.cmd`` targets are affected: everything else is handed to
    ``CreateProcess`` as a real executable and no command interpreter sees it.
    """
    argv = [str(a) for a in (command or [])]
    if not argv:
        return None
    exe = argv[0]
    if not exe.lower().endswith((".bat", ".cmd")):
        return None
    quoted = subprocess.list2cmdline(argv).startswith('"')
    for ch in exe:
        if ch in CMD_UNSAFE_ALWAYS:
            return ch
        if ch in CMD_UNSAFE_UNQUOTED and not quoted:
            return ch
    return None


def _mark_cmd_hazard(entry: dict) -> dict:
    """Refuse an entry whose own path would be re-parsed by ``cmd.exe``."""
    hazard = cmd_line_hazard(entry.get("command"))
    if hazard is not None:
        entry["available"] = False
        entry["unsafe_reason"] = "cmd_metacharacter_in_path"
        entry["note"] = (
            f"Refused: the path contains '{hazard}', which cmd.exe would treat "
            "as syntax rather than as part of the filename when it runs a batch "
            "file. Rename it, or start ComfyUI yourself.")
    return entry

