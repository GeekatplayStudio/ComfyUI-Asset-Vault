MAX_OUTPUT_LINES = 4000
UPDATE_TIMEOUT_S = 30 * 60


def resolve_updater(updater_id: str | None = None, cfg=None) -> dict:
    install = probe(cfg)
    if not install.updaters:
        raise NotFoundError(
            "No update mechanism was found for this ComfyUI installation.",
            details={"comfyui_path": str(install.root) if install.root else None,
                     "flavour": install.flavour,
                     "hint": "A portable build keeps update_comfyui.bat in an "
                             "'update' folder beside the ComfyUI folder."},
        )
    if updater_id:
        for entry in install.updaters:
            if entry["id"] == updater_id:
                chosen = entry
                break
        else:
            raise NotFoundError(
                f"'{updater_id}' is not an updater this install offers.",
                details={"available": [e["id"] for e in install.updaters]})
    else:
        chosen = next(e for e in install.updaters if e["recommended"])
    if not chosen.get("available"):
        raise ConflictError(
            f"{chosen['label']} was found but cannot be run.",
            details={"updater": chosen["id"], "path": chosen.get("path")})
    return chosen


def update_status() -> dict:
    state = dict(_run_state)
    state["running"] = state.get("status") == "running"
    return state


def run_updater(updater_id: str | None, *, confirm_path: str,
                trigger: str = "api") -> dict:
    """Run the discovered updater.  The one subprocess this app ever starts.

    ``confirm_path`` must equal the resolved absolute path of the chosen updater.
    That is not ceremony: it is what makes the confirmation dialog's promise -
    "this exact file will be executed" - structurally true, and it means a
    stale UI or a mistaken MCP call cannot run something the user never saw.
    """
    chosen = resolve_updater(updater_id)
    resolved = str(normalize(chosen["path"])) if chosen.get("path") else ""
    if not confirm_path or str(normalize(confirm_path)) != resolved:
        raise ValidationError(
            "The update was not confirmed for the path that would actually run.",
            details={"resolved_path": resolved, "confirm_path": confirm_path,
                     "hint": "Send confirm_path exactly as returned by "
                             "GET /api/v1/comfyui/update/plan."},
        )
    running = is_running()
    if running["running"]:
        raise ConflictError(
            "ComfyUI appears to be running. Close it before updating.",
            details=running)

    with _run_lock:
        if _run_state.get("status") == "running":
            raise ConflictError("An update is already running.",
                                details={"started_at": _run_state.get("started_at")})
        _run_state.clear()
        _run_state.update({
            "status": "running", "updater": chosen["id"], "path": resolved,
            "command": chosen["command"], "started_at": dbmod.now_ms(),
            "trigger": trigger, "lines": 0, "exit_code": None,
        })

    thread = threading.Thread(target=_run_updater_thread,
                              args=(chosen, resolved), daemon=True,
                              name="comfyui-update")
    thread.start()
    UPDATE_CHANNEL.publish("phase", {"phase": "starting", "updater": chosen["id"],
                                     "path": resolved})
    return {
        "started": True, "updater": chosen["id"], "label": chosen["label"],
        "path": resolved, "working_dir": chosen["working_dir"],
        "stream": "/api/v1/comfyui/update/stream",
        "started_at": _run_state["started_at"],
    }


def _run_updater_thread(chosen: dict, resolved: str) -> None:
    started = time.perf_counter()
    lines = 0
    exit_code: int | None = None
    error: str | None = None
    try:
        # A list argv with shell=False: nothing here is ever assembled from user
        # text, and the executable is one of the paths `discover_updaters` found
        # on disk.
        proc = subprocess.Popen(  # noqa: S603
            list(chosen["command"]),
            cwd=chosen.get("working_dir") or None,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL, text=True, encoding="utf-8",
            errors="replace", bufsize=1,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except OSError as exc:
        error = str(exc)[:400]
        UPDATE_CHANNEL.publish("error", {"message": error})
    else:
        assert proc.stdout is not None
        try:
            for raw in proc.stdout:
                line = raw.rstrip("\r\n")
                lines += 1
                if lines <= MAX_OUTPUT_LINES:
                    UPDATE_CHANNEL.publish("output", {"line": line[:2000],
                                                      "n": lines})
                elif lines == MAX_OUTPUT_LINES + 1:
                    UPDATE_CHANNEL.publish(
                        "output", {"line": "... output truncated ...", "n": lines})
                _run_state["lines"] = lines
                if time.perf_counter() - started > UPDATE_TIMEOUT_S:
                    proc.kill()
                    error = "The updater exceeded its time limit and was stopped."
                    break
            exit_code = proc.wait(timeout=60)
        except Exception as exc:  # noqa: BLE001 - reported, never raised into a thread
            error = str(exc)[:400]
            with contextlib.suppress(OSError, ValueError):
                proc.kill()

    duration = int((time.perf_counter() - started) * 1000)
    after = probe()
    payload = {
        "status": "completed" if exit_code == 0 and not error else "failed",
        "updater": chosen["id"], "path": resolved, "exit_code": exit_code,
        "error": error, "duration_ms": duration, "lines": lines,
        "version_after": after.version,
        "finished_at": dbmod.now_ms(),
        "restart_required": True,
        "note": ("ComfyUI was updated. Restart ComfyUI, then re-scan the vault "
                 "so new bundled workflows and node classes are picked up."),
    }
    with _run_lock:
        _run_state.update(payload)
        _run_state["running"] = False
    UPDATE_CHANNEL.publish("done", payload)


