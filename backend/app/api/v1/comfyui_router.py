"""``/api/v1/comfyui`` - version, updater, official templates, and opening a
workflow inside ComfyUI (C8).

Two routes here can start a process: the updater run route and the open-workflow
route when it is asked to start ComfyUI.  Both use the same deliberately awkward
contract: the caller first fetches the matching plan route, shows the resolved
absolute path, and sends that exact path back as a confirmation field.  A
confirmation that does not name what will run is not a confirmation, and
clicking "open a workflow" is never on its own consent to start a program.

Everything else here is read-only.
"""

