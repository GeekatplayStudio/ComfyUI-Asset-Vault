def test_updaters_are_discovered_beside_the_comfyui_folder(portable):
    updaters = {u["id"]: u for u in cs.probe().updaters}
    assert "portable" in updaters, "update/update_comfyui.bat was not found"
    assert "portable_stable" in updaters
    chosen = updaters["portable"]
    assert chosen["recommended"]
    assert Path(chosen["path"]).name == "update_comfyui.bat"
    assert Path(chosen["path"]).is_file()
    assert chosen["command"] == [chosen["path"]]


def test_updater_discovery_reports_nothing_rather_than_guessing(tmp_path):
    """An install with no updater must say so, not invent a path."""
    db = tmp_path / "bare.db"
    original = dbmod.db_path()
    dbmod.set_db_path(db)
    try:
        migrate()
        config_service.invalidate()
        root = tmp_path / "bare" / "ComfyUI"
        (root / "models").mkdir(parents=True)
        (root / "main.py").write_text("#\n", encoding="utf-8")
        config_service.set_config({"comfyui_path": str(root)})
        assert cs.probe().updaters == []
        with pytest.raises(NotFoundError):
            cs.resolve_updater()
    finally:
        dbmod.shutdown_writer()
        dbmod.close_thread_connections()
        dbmod.set_db_path(original)
        config_service.invalidate()


def test_run_refuses_a_confirmation_that_names_the_wrong_path(portable):
    """The rail that makes 'you are about to run X' true (C8.3)."""
    with pytest.raises(ValidationError) as excinfo:
        cs.run_updater("portable", confirm_path=str(portable["base"] / "nope.bat"))
    details = excinfo.value.details
    assert details["resolved_path"].endswith("update_comfyui.bat")
    assert cs.update_status()["status"] != "running", "nothing may have started"


def test_run_refuses_an_empty_confirmation(portable):
    with pytest.raises(ValidationError):
        cs.run_updater("portable", confirm_path="")
    assert cs.update_status()["status"] != "running"


def test_unknown_updater_is_rejected_before_anything_resolves(portable):
    with pytest.raises(NotFoundError):
        cs.resolve_updater("definitely-not-an-updater")


def test_running_probe_is_honest_about_its_confidence(portable):
    probe = cs.is_running()
    assert probe["confidence"] == "inferred"
    assert "method" in probe and probe["note"]


