def _portable(base: Path, version: str = "0.33.0") -> Path:
    """The real portable layout: ComfyUI, python_embeded and update as siblings."""
    root = base / "ComfyUI"
    (root / "models" / "checkpoints").mkdir(parents=True, exist_ok=True)
    (root / "custom_nodes").mkdir(parents=True, exist_ok=True)
    (root / "output").mkdir(parents=True, exist_ok=True)
    (root / "main.py").write_text("# ComfyUI\n", encoding="utf-8")
    (root / "comfyui_version.py").write_text(
        "# generated by the build\n"
        f'__version__ = "{version}"\n', encoding="utf-8")

    site = base / "python_embeded" / "Lib" / "site-packages"
    site.mkdir(parents=True, exist_ok=True)
    (base / "python_embeded" / "python.exe").write_bytes(b"MZ")
    for dist, dist_version in (("comfyui_frontend_package", "1.49.6"),
                               ("comfyui_workflow_templates_json", "0.1.49"),
                               ("comfyui_embedded_docs", "0.5.10")):
        (site / f"{dist}-{dist_version}.dist-info").mkdir(exist_ok=True)
    templates = site / "comfyui_workflow_templates_json" / "templates"
    templates.mkdir(parents=True, exist_ok=True)
    for name in ("alpha_flow", "beta_flow"):
        (templates / f"{name}.json").write_text('{"nodes": []}', encoding="utf-8")

    update = base / "update"
    update.mkdir(exist_ok=True)
    (update / "update_comfyui.bat").write_text("@echo off\n", encoding="utf-8")
    (update / "update_comfyui_stable.bat").write_text("@echo off\n", encoding="utf-8")
    (base / "run_nvidia_gpu.bat").write_text("@echo off\n", encoding="utf-8")
    return root


@pytest.fixture
def portable(tmp_path):
    db = tmp_path / "comfyui.db"
    original = dbmod.db_path()
    dbmod.set_db_path(db)
    migrate()
    config_service.invalidate()
    root = _portable(tmp_path)
    config_service.set_config({"comfyui_path": str(root), "is_configured": True})
    yield {"root": root, "base": tmp_path}
    dbmod.shutdown_writer()
    dbmod.close_thread_connections()
    dbmod.set_db_path(original)
    config_service.invalidate()


