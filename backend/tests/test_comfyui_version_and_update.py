def test_official_templates_are_catalogued_read_only(portable):
    catalogue = cs.template_catalogue()
    assert catalogue["available"]
    assert catalogue["total"] == 2
    assert {i["id"] for i in catalogue["items"]} == {"alpha_flow", "beta_flow"}
    assert all(i["origin"] == "official_template" for i in catalogue["items"])
    assert "not indexed" in (catalogue["note"] or "")


def test_template_catalogue_says_why_when_unavailable(tmp_path):
    db = tmp_path / "notpl.db"
    original = dbmod.db_path()
    dbmod.set_db_path(db)
    try:
        migrate()
        config_service.invalidate()
        root = tmp_path / "plain" / "ComfyUI"
        (root / "models").mkdir(parents=True)
        (root / "main.py").write_text("#\n", encoding="utf-8")
        config_service.set_config({"comfyui_path": str(root)})
        catalogue = cs.template_catalogue()
        assert not catalogue["available"]
        assert catalogue["reason"]
    finally:
        dbmod.shutdown_writer()
        dbmod.close_thread_connections()
        dbmod.set_db_path(original)
        config_service.invalidate()


@pytest.mark.parametrize(("rel_path", "origin", "package"), [
    ("custom_nodes/ComfyUI-WanVideoWrapper/example_workflows/i2v.json",
     "bundled", "ComfyUI-WanVideoWrapper"),
    ("custom_nodes/QR/workflows/qr.json", "bundled", "QR"),
    ("user/default/workflows/mine.json", "user", None),
    ("workflows/Anime/portrait.json", "user", None),
    ("workflows/ComfyUI-LTXVideo/example_workflows/2.0/t2v.json", "user", None),
    ("solo.json", "user", None),
])
def test_workflow_origin_classification(rel_path, origin, package):
    assert workflow_origin.classify(rel_path) == (origin, package)


def test_origin_labels_read_the_way_the_requirement_words_them():
    assert workflow_origin.label("user", None) == "user"
    assert workflow_origin.label("official_template", None) == "official template"
    assert workflow_origin.label("bundled", "QR") == "bundled with QR"


def test_copied_bundles_expose_a_hint_but_stay_user_owned():
    """A graph the owner copied into their own folder is theirs; the package it
    came from is a hint, not a reclassification."""
    rel = "workflows/ComfyUI-LTXVideo/example_workflows/2.0/t2v.json"
    assert workflow_origin.classify(rel)[0] == "user"
    assert workflow_origin.example_dir_hint(rel) == "ComfyUI-LTXVideo"
