def test_version_is_read_not_executed(portable):
    install = cs.probe()
    assert install.version == "0.33.0"
    assert install.version_source == "comfyui_version.py"


def test_flavour_and_evidence(portable):
    install = cs.probe()
    assert install.flavour == "portable"
    assert install.flavour_reasons, "the UI must be able to say *why* it decided"
    assert install.python and "python_embeded" in install.python


def test_frontend_and_template_package_versions(portable):
    packages = cs.probe().packages
    assert packages.get("comfyui_frontend_package") == "1.49.6"
    assert packages.get("comfyui_workflow_templates_json") == "0.1.49"


def test_version_comparison(portable):
    assert cs.compare_versions("0.33.0", "0.34.1") == "behind"
    assert cs.compare_versions("0.33.0", "0.33.0") == "current"
    assert cs.compare_versions("0.34.0", "v0.33.0") == "ahead"
    assert cs.compare_versions(None, "0.33.0") == "unknown"
    assert cs.compare_versions("0.33.0", "nightly") == "unknown"


