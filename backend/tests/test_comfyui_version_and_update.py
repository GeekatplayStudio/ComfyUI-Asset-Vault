def test_latest_check_is_a_plain_answer_when_offline(portable):
    import asyncio

    result = asyncio.run(cs.check_latest())
    assert result["installed"] == "0.33.0"
    assert result["state"] in ("current", "behind", "ahead", "unknown")
    assert result["reason"] == "online_disabled"
    assert result["latest"] is None


